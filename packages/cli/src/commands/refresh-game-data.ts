import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { extractIoStoreFile, parseGameItems, GAME_PAKS, GAME_TOC, gameSourceFiles, patchContainersWithAsset, KdecDecoder, parseEnemiesTable, type Decoder } from '@af-ledger/core';
import { configDir, kdecPath } from '../paths';
import { outputBlocked } from '../png';
import { oneLine } from '../format';
import type { Command } from '../run';

const ASSET = 'DataTables/DT_Enemies.uasset';

type Extract = (utoc: string, suffix: string, decoder: Decoder) => Promise<Uint8Array>;

export function createRefreshGameDataCommand(extract: Extract = extractIoStoreFile): Command {
  return {
    options: { 'game-dir': { type: 'string' }, output: { type: 'string' } },
    async run({ values }, io) {
      const game = values['game-dir'] as string | undefined || io.env.AF_GAME_DIR;
      if (!game) {
        io.err('af-ledger refresh-game-data: provide --game-dir <dir> or AF_GAME_DIR\n');
        return 2;
      }
      try {
        const output = path.resolve(values.output as string | undefined || path.join(configDir(), 'game-items.json'));
        // Protect the configured install too, so --game-dir pointing at a copy can't write into the real one.
        const blocked = outputBlocked(output, '', io.env, { label: 'output', gameDirs: [game, io.env.AF_GAME_DIR ?? ''] });
        if (blocked) throw new Error(blocked);
        const patches = await patchContainersWithAsset(game, ASSET);
        if (patches.length) throw new Error(`patch containers aren't supported yet: ${patches.join(', ')}`);
        const utoc = path.join(game, GAME_PAKS, GAME_TOC);
        const files = await gameSourceFiles(game);
        const rows = parseEnemiesTable(await extract(utoc, ASSET, new KdecDecoder(kdecPath(io.env))));
        const duplicates = [...new Set(rows.map((row) => row.row).filter((name, i, all) => all.indexOf(name) !== i))];
        if (duplicates.length) throw new Error(`duplicate DT_Enemies rows: ${duplicates.join(', ')}; game data format may have changed`);
        const exact = rows.filter((row) => row.exact);
        const skipped = rows.filter((row) => !row.exact).map((row) => row.row);
        if (skipped.length > 5 || exact.length < 150) {
          throw new Error(`only ${exact.length} exact rows, ${skipped.length} skipped; game data format may have changed (need >=150 exact and <=5 skipped)`);
        }
        const data = {
          _comment: "Generated by `npm run refresh:game-data` from the game's DT_Enemies table. Do not edit by hand. Money in copper.",
          _source: { files, asset: ASSET, rows: rows.length, skipped },
          items: Object.fromEntries(exact.map(({ row, item }) => [row, item])),
        };
        const text = `${JSON.stringify(data, null, 2)}\n`;
        // Never replace a good file with one the ledger would refuse to load.
        parseGameItems(JSON.parse(text), 'extracted game data');
        await mkdir(path.dirname(output), { recursive: true });
        await writeFile(output, text, 'utf8');
        io.out(`${exact.length} rows written, ${skipped.length} rows skipped -> ${output}\n`);
        return 0;
      } catch (error) {
        io.err(`af-ledger refresh-game-data: ${oneLine((error as Error).message)}\n`);
        return 1;
      }
    },
  };
}

export const refreshGameData = createRefreshGameDataCommand();
